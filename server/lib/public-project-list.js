export const serializePublicProjectCatalogItem = (project = {}) => ({
  id: project.id,
  title: project.title,
  titleOriginal: project.titleOriginal,
  titleEnglish: project.titleEnglish,
  synopsis: project.synopsis,
  description: project.description,
  type: project.type,
  status: project.status,
  studio: project.studio,
  animationStudios: project.animationStudios,
  episodes: project.episodes,
  tags: project.tags,
  genres: project.genres,
  cover: project.cover,
  coverAlt: project.coverAlt,
  producers: project.producers,
});

export const serializePublicProjectCatalog = (projects) =>
  (Array.isArray(projects) ? projects : []).map(serializePublicProjectCatalogItem);

